def main() -> int:
    rows: list[tuple[str, str]] = []
    seen: set[tuple[str, str]] = set()

    def add(key: str, value: str) -> None:
        if "\t" in value or "\n" in value:
            raise ValueError(f"{value!r} must be one line without tabs")
        if (key, value) not in seen:
            seen.add((key, value))
            rows.append((key, value))

    for face, readings in FACES:
        for reading in readings.split():
            add(reading, face)
    for art, readings in ART:
        for reading in readings.split():
            add(reading, art)
    for face, _ in FACES:
        add(ALL_FACES, face)
    for art, _ in ART:
        for key in ALL_ART:
            add(key, art)
    english: list[tuple[str, str]] = []
    seen_english: set[tuple[str, str]] = set()
    for value, readings in FACES + ART:
        for reading in readings.split():
            for name in ENGLISH.get(reading, "").split():
                if (name, value) not in seen_english:
                    seen_english.add((name, value))
                    english.append((name, value))
    for face, _ in FACES:
        english.append((ALL_FACES_EN, face))
    for art, _ in ART:
        english.append((ALL_ART_EN, art))

    PACK.mkdir(parents=True, exist_ok=True)
    lines = ["# Kaomoji and one-line ASCII art by reading, written for TEKITO (scripts/build-kaomoji-pack.py)."]
    lines += [f"emoticon\tja\t{key}\t{value}" for key, value in rows]
    lines += [f"symbolname\ten\t{key}\t{value}" for key, value in english]
    data = ("\n".join(lines) + "\n").encode("utf-8")
    (PACK / "rules.tsv").write_bytes(data)
    (PACK / "NOTICE").write_text(
        "The kaomoji pack's emoticons and ASCII art were collected and written for TEKITO.\n",
        encoding="utf-8", newline="\n")
    manifest = {
        "pack_id": "kaomoji",
        "display_name": "Kaomoji and ASCII Art",
        "schema_version": 1,
        "version": VERSION,
        "language": "ja-JP+en-US",
        "type": "special-conversions",
        "format": "rules-tsv-v1",
        "file": "rules.tsv",
        "entry_count": len(rows) + len(english),
        "sha256": {"file": hashlib.sha256(data).hexdigest().upper()},
        "license": "TEKITO-OWNED",
        "source": "scripts/build-kaomoji-pack.py",
        "notice_file": "NOTICE",
    }
    (PACK / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
                                        encoding="utf-8", newline="\n")
    print(f"{len(FACES)} faces, {len(ART)} pieces of art, {len(rows)} Japanese rows, {len(english)} English rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
