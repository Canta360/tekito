// The language the page should show: the setting, or Windows' language.
export function resolveLanguage(uiLanguage, systemLanguage) {
  if (uiLanguage === 1) return "en";
  if (uiLanguage === 2) return "ja";
  return systemLanguage === "ja" ? "ja" : "en";
}

